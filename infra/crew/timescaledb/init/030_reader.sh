#!/bin/sh
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<SQL
DO \$\$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${CREW_READER_USER}') THEN
    CREATE ROLE ${CREW_READER_USER} LOGIN PASSWORD '${CREW_READER_PASSWORD}' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;
  END IF;
END \$\$;
ALTER ROLE ${CREW_READER_USER} SET statement_timeout = '5s';
SQL
